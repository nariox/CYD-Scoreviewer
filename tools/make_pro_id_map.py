#!/usr/bin/env python3
"""Regenerate main/pro_team_ids.c/.h - ESPN pro team id -> feed (balldontlie)
team id, for the NBA and WNBA scoreboards.

Why this table exists: all four feeds ride ESPN's scoreboard now, but the
baked logo tables (team_logos.c) and the pro arena table (team_venues.c) are
keyed by *balldontlie* team id - the id namespace the whole firmware used
before the ESPN migration. ESPN's NBA/WNBA ids are a different numbering that
OVERLAPS the balldontlie range (ESPN 2 = Boston, balldontlie 2 = Brooklyn),
so a raw ESPN id would silently draw the wrong logo. espn_api maps every pro
competitor through this table at parse time; anything not listed lands on 0
(placeholder ring), never a raw ESPN id.

Data sources:
  balldontlie side  tools/logos/teams_{nba,wnba}.json  (frozen snapshots of
                    /nba|wnba/v1/teams - balldontlie is retired, do not re-walk)
  ESPN side         site.api.espn.com/.../basketball/{nba,wnba}/teams
                    cached as tools/logos/espn_teams_{nba,wnba}.json

Join key is the team FULL NAME - the proven rule (ESPN's pro abbreviations
differ from balldontlie's: NY vs NYK, WSH vs WAS). The table is capped to the
current balldontlie namespace (NBA 1..30, WNBA 1..13); ESPN also lists dead
franchises (Portland Fire) and expansion teams the logo table has not baked
yet (Toronto Tempo) - those stay out, print as warnings, and draw the ring.

Usage:
  python3 tools/make_pro_id_map.py            # offline when both caches exist
  python3 tools/make_pro_id_map.py --refresh  # re-fetch ESPN's team lists
"""

import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / "tools" / "logos"
OUT_H = ROOT / "cyd_basketball_scores" / "main" / "pro_team_ids.h"
OUT_C = ROOT / "cyd_basketball_scores" / "main" / "pro_team_ids.c"

# balldontlie's current namespaces (see AGENTS: the roster lists retired BAA
# and Euro clubs past these caps; the baked tables stop here too).
CAPS = {"nba": 30, "wnba": 13}
ESPN_URL = ("https://site.api.espn.com/apis/site/v2/sports/basketball/"
            "{lg}/teams?limit=120")
UA = {"User-Agent": "Mozilla/5.0"}


def espn_teams(lg: str, refresh: bool) -> dict[str, int]:
    """ESPN site team id by full display name."""
    path = CACHE / f"espn_teams_{lg}.json"
    if refresh or not path.exists():
        url = ESPN_URL.format(lg=lg)
        req = urllib.request.Request(url, headers=UA)
        with urllib.request.urlopen(req, timeout=30) as resp:
            path.write_bytes(resp.read())
        print(f"  fetched {url}")
    data = json.loads(path.read_text())
    teams = data["sports"][0]["leagues"][0]["teams"]
    return {t["team"]["displayName"]: int(t["team"]["id"]) for t in teams}


def balldontlie_current(lg: str) -> dict[str, int]:
    """full name -> balldontlie id, capped to the live namespace."""
    path = CACHE / f"teams_{lg}.json"
    data = json.loads(path.read_text())["data"]
    return {t["full_name"]: t["id"] for t in data if 1 <= t["id"] <= CAPS[lg]}


def build(lg: str, refresh: bool):
    espn = espn_teams(lg, refresh)
    feed = balldontlie_current(lg)
    pairs = sorted((e_id, f_id) for name, f_id in feed.items()
                   for e_id in [espn.get(name)] if e_id is not None)
    missing = [n for n in feed if n not in espn]
    extra = [n for n in espn if n not in feed]
    print(f"{lg}: mapped {len(pairs)}/{len(feed)}"
          + (f" | MISSING on ESPN: {missing}" if missing else "")
          + (f" | ESPN-only (unmapped -> ring): {extra}" if extra else ""))
    if len(pairs) != len(feed):
        print(f"  WARNING: {lg} join incomplete - check full-name drift",
              file=sys.stderr)
    return pairs


def emit(pairs_by_lg: dict[str, list[tuple[int, int]]]):
    hdr = """/* GENERATED by tools/make_pro_id_map.py - do not edit.
 * ESPN pro team id -> balldontlie (feed) team id. The baked logo and arena
 * tables are keyed by balldontlie id while the ESPN scoreboard carries ESPN
 * ids from an OVERLAPPING namespace, so espn_api maps pro competitors through
 * this table; an unmapped id must become 0, never the raw ESPN id.
 */
#pragma once

#include "nba_api.h"          /* league_t */

/* balldontlie-space id for an ESPN scoreboard team id, 0 when unknown. */
int espn_pro_feed_id(league_t lg, int espn_id);
"""
    OUT_H.write_text(hdr)

    body = ['/* GENERATED by tools/make_pro_id_map.py - do not edit. */',
            '#include "pro_team_ids.h"',
            '',
            'typedef struct { int espn_id, feed_id; } pro_id_pair_t;',
            '']
    for lg, name in (("nba", "s_nba"), ("wnba", "s_wnba")):
        pairs = pairs_by_lg[lg]
        body.append(f"static const pro_id_pair_t {name}[] = {{")
        for e_id, f_id in pairs:
            body.append(f"    {{{e_id:6d}, {f_id:2d}}},")
        body.append("};")
        body.append(f"#define N_{name} ((int)(sizeof({name}) / sizeof({name}[0])))")
        body.append("")
    body.append("""int espn_pro_feed_id(league_t lg, int espn_id)
{
    if (espn_id <= 0) {
        return 0;
    }
    /* 13-30 sorted entries per league, two lookups per fetched game: a linear
       scan beats a binary search at this size and keeps the two layouts
       identical. Unknown (dead franchise, expansion team not baked yet):
       0 = logo placeholder, never a wrong-logo collision. */
    const pro_id_pair_t *p = (lg == LEAGUE_WNBA) ? s_wnba : s_nba;
    const int n = (lg == LEAGUE_WNBA) ? N_s_wnba : N_s_nba;
    for (int i = 0; i < n; i++) {
        if (p[i].espn_id == espn_id) {
            return p[i].feed_id;
        }
    }
    return 0;
}
""")
    OUT_C.write_text("\n".join(body))
    print(f"wrote {OUT_C}")


def main():
    refresh = "--refresh" in sys.argv
    CACHE.mkdir(parents=True, exist_ok=True)
    pairs = {lg: build(lg, refresh) for lg in ("nba", "wnba")}
    emit(pairs)


if __name__ == "__main__":
    main()
